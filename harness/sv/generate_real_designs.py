#!/usr/bin/env python3
"""Generate the public REAL-DESIGNS admission table from pinned receipts."""

from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "sv-real-designs.md"

# These are the checked-in census receipts for the pinned public sources.  The
# output table is generated; changing a result requires changing its measured
# receipt and rerunning this script.
ROWS = [
    ("prim_fifo_sync", "OpenTitan 0a6ff685", "36", "yes", "canonical-E hierarchy admission at defaults; 8-cycle ordinary-E trace matches Xcelium 24.03-s004; Icarus 13.0 refuses the unchanged source at its packed-array parameter frontend wall; source-shaped diagnostic $error and #1ps checks are admitted only by the elaboration-check adapter"),
    ("prim_arbiter_ppc", "OpenTitan 0a6ff685", "0", "yes", "canonical-E hierarchy admission and initialState at N=8,DW=32,EnDataPort=1; source-shaped loop family measured separately at N=2/N=4 with 16/16 rows matching both pinned simulators"),
    ("prim_packer", "OpenTitan 0a6ff685", "20", "yes", "canonical-E hierarchy admission at defaults; fixed module-local scalar enum and prim_count child parameter override admitted; remaining source-shaped wall is diagnostic $error"),
    ("CV32E40P", "openhwgroup v1.0.1 / 6148cf5", "574", "yes", "Structure=true; EquationGate=false at the sole retained always_comb process (index 10: State_SN, OutVld_SO, enables, and case body); canonical-E complete equation tier remains outside admission"),
    ("Ibex", "lowRISC d513671d", "396", "no", "AlwaysLatch:unknown process kind"),
    ("PicoRV32", "YosysHQ ef203c2b", "0", "yes", "time-zero initialState + input-driven RVFI E-RUN: 220/220 cycles agree with both pinned simulators; census 360 admitted, 0 refused, 4 not reached"),
    ("DarkRISCV", "darklife bb6b483c", "0", "yes", "177 admitted / 0 refused / 0 not reached; staged canonical-E clock probe 4/4; 1000 source-shaped rising-edge cycles complete"),
    ("FemtoRV32 Quark", "BrunoLevy/learn-fpga f5ada24a", "48", "no", "Constant:untyped-width at FETCH_INSTR; canonical-E E-RUN 0/0; both pinned simulators refuse before elaboration at use-before-declared instr"),
]

lines = [
    "# REAL-DESIGNS admission census",
    "",
    "<!-- GENERATED by harness/sv/generate_real_designs.py; do not edit. -->",
    "",
    "This table is generated from the pinned public-design census receipts. It measures loading and the first E wall for each source as written; no RTL was adapted.",
    "",
    "| design | pinned source | unsupported nodes | loads into E | first E wall |",
    "| --- | --- | ---: | --- | --- |",
]
for row in ROWS:
    lines.append("| `%s` | %s | %s | %s | `%s` |" % row)
lines += ["", "The three OpenTitan rows use the F1-retention census in `docs/sv-frontier.md`; CV32E40P and the RISC-V scouting rows use `Examples/system-verilog/cores/README.md` and `docs/cv32e40p-census.json`. The table is an admission census, not a proof claim.", ""]
generated = "\n".join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true",
                    help="verify the checked-in page is exactly generated")
args = parser.parse_args()
if args.check:
    current = OUT.read_text() if OUT.exists() else None
    if current != generated:
        raise SystemExit(f"generated page is stale: {OUT}")
    print(f"checked {OUT}")
else:
    OUT.write_text(generated)
    print(OUT)
