#!/usr/bin/env python3
"""Render the dated effective-type pointer-bit-cast audit.

The replay input is produced by the pinned Clang/model runner outside the
repository.  This renderer keeps the source names and observed outcomes
portable, then emits the reviewable Markdown and JSON receipts.
"""
import argparse, json
from pathlib import Path

CLAUSE = "C23 §6.5.1p6–p7"
ROWS = [
    "00103.c", "00170.c", "20060412-1.c", "991228-1.c", "alias-1.c",
    "enum-3.c", "gcc/testsuite/gcc.dg/c23-tag-alias-4.c", "mayalias-1.c",
    "mayalias-2.c", "mayalias-3.c", "pr10352-1.c", "pr28778.c", "pr36343.c",
    "pr41317.c", "pr43987.c", "pr60003.c", "pr79043.c", "pta-field-1.c",
    "pta-field-2.c", "struct-aliasing-1.c",
]

def load(path):
    rows = {}
    for line in Path(path).read_text().splitlines():
        if line.strip():
            item = json.loads(line)
            name = item["name"]
            rows[name if "." in name.rsplit("/", 1)[-1] else name + ".c"] = item
    missing = [name for name in ROWS if name not in rows]
    if missing:
        raise SystemExit("missing replay rows: " + ", ".join(missing))
    return [rows[name] for name in ROWS]

def status(item):
    model = item["model"]
    if model[1] == 3:
        return "REFUSE", model[3]
    if model[1] == 4:
        return "TIMEOUT", model[3]
    if model[1] == 0:
        return "MODEL 0", model[2]
    return "RUNNER", model[3] if len(model) > 3 else ""

def display_name(name):
    return name if "." in name.rsplit("/", 1)[-1] else name + ".c"

def native_summary(item):
    o0, o2, san = item.get("o0"), item.get("o2"), item.get("san")
    if not o0:
        return "no oracle result"
    if o0[0] == "compile" or o2[0] == "compile" or san[0] == "compile":
        return "compile failure"
    if (o0[0], o0[1]) != (o2[0], o2[1]):
        return "NONDET O0/O2"
    if san[0] == o0[0] and san[1] == o0[1] and san[2] == o0[2]:
        return f"O0/O2/san rc {o0[0]}"
    return "sanitizer differs"

def render(rows):
    counts = {}
    for row in rows:
        s, _ = status(row)
        counts[s] = counts.get(s, 0) + 1
    lines = [
        "# Effective-type pointer-bit-cast audit, 2026-11-28", "",
        "Generated by `harness/c_effective_type_audit.py` from a focused replay "
        "of the 20 rows whose committed survey wall is `pointer bit-cast across "
        "incompatible effective types`. Sources are unchanged corpus files. "
        "The pinned oracle is Clang 21.1.8 with C23, O0, O2 and UBSan/ASan.", "",
        f"Counts in the current replay: {', '.join(f'{k} {v}' for k,v in sorted(counts.items()))}.", "",
        "The two wrong answers found in this replay were `alias-1.c` and "
        "`pr79043.c`. Their float stores into declared `int` objects now stop "
        f"with `{CLAUSE}` instead of producing a value. The native runs are clean, "
        "so the clause and source operand are the UB witnesses.", "",
        "`pr60003.c` has no oracle result because O0 and O2 terminate differently "
        "in the builtin setjmp/longjmp path. It remains a loud library refusal.", "",
        "| row | model | native | interpretation |", "| --- | --- | --- | --- |",
    ]
    for row in rows:
        s, detail = status(row)
        native = native_summary(row)
        name = display_name(row["name"])
        if name in ("alias-1.c", "pr79043.c"):
            interpretation = "wrong answer closed, effective-type UB refusal"
        elif s == "REFUSE":
            interpretation = "loud refusal, " + CLAUSE if "effectiveType" in detail else "loud refusal, no oracle claim"
        else:
            interpretation = "model/native agree; no new admission is claimed by this audit"
        lines.append(f"| `{name}` | `{s}` | `{native}` | {interpretation} |")
    lines += ["", "The remaining admitted rows are retained for the separate provenance, "
              "subobject and byte-representation work. This item changes only the "
              "floating-store effective-type check.", ""]
    return "\n".join(lines)

def self_test():
    item = {"name": "alias-1.c", "model": ["model", 3, "", "effectiveType"],
            "o0": [0, "", ""], "o2": [0, "", ""], "san": [0, "", ""]}
    assert status(item)[0] == "REFUSE"
    assert "O0/O2/san" in native_summary(item)
    print("c_effective_type_audit --self-test: ok")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--replay")
    ap.add_argument("--output", default="docs/c-effective-type-bitcast-audit-20261128.md")
    ap.add_argument("--json", default="docs/c-effective-type-bitcast-audit-20261128.json")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test(); return 0
    if not args.replay:
        ap.error("--replay is required")
    rows = load(args.replay)
    Path(args.output).write_text(render(rows))
    Path(args.json).write_text(json.dumps({"schema": "c-effective-type-audit-1", "rows": rows}, indent=1) + "\n")
    print(f"c_effective_type_audit: wrote {args.output} and {args.json}")

if __name__ == "__main__":
    main()
